//Este reto consiste en mostrar los números del 1 al 10 con for
public class Reto1 {
    public static void main(String[] args) {
        // El ciclo arranca en 1 y se repite mientras sea menor o igual a 10
        for (int numero = 1; numero <= 10; numero++) {
            System.out.println(numero);
        }
    }
}
